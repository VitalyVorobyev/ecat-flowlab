import { Badge, type Tone } from "@vitavision/ui";

import type { Provenance } from "../api";

const TONE: Record<Provenance, Tone> = {
  measured: "neutral",
  simulated: "info",
  synthetic: "info",
};
const TEXT: Record<Provenance, string> = {
  measured: "Measured",
  simulated: "Simulated",
  synthetic: "Synthetic",
};
const HINT: Record<Provenance, string> = {
  measured: "From a capture file. FlowLab cannot verify how it was recorded.",
  simulated: "Produced by the FlowLab simulator from a model; a prediction, not a measurement.",
  synthetic: "Generated by flowlab synth with known ground truth; for testing and demos.",
};

/** Where the data came from. Shown wherever results are shown. */
export function ProvenanceBadge({ provenance }: { provenance: Provenance }) {
  return (
    <span title={HINT[provenance]}>
      <Badge tone={TONE[provenance]}>{TEXT[provenance]}</Badge>
    </span>
  );
}
