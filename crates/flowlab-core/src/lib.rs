//! Shared vocabulary of ECAT FlowLab: where a result came from ([`Provenance`]),
//! the metadata every report carries ([`ReportMeta`]), and unit helpers.
//!
//! Units are carried in field names (`_ns`, `_bytes`, `_bps`) rather than newtypes, so the
//! JSON reports stay self-describing for tools outside Rust.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

pub mod pdi_samples;
pub mod rng;
pub mod stats;
pub mod units;

/// Version of the JSON report schemas. Bump on any breaking change.
pub const SCHEMA_VERSION: u32 = 1;

/// Where the data behind a result came from. Every report and every UI view shows it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum Provenance {
    /// Captured from a real network. FlowLab cannot verify this; it is the default for
    /// files that do not declare otherwise.
    Measured,
    /// Produced by the FlowLab discrete-event simulator from a model.
    Simulated,
    /// Generated by `flowlab synth` with known ground truth, for testing and demos.
    Synthetic,
}

impl Provenance {
    /// Marker written into pcapng section comments by FlowLab generators.
    pub const COMMENT_PREFIX: &'static str = "flowlab:provenance=";

    /// Lower-case name as used in JSON and in the pcapng marker.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Measured => "measured",
            Self::Simulated => "simulated",
            Self::Synthetic => "synthetic",
        }
    }

    /// Parse a FlowLab provenance marker out of a free-text comment.
    pub fn from_comment(comment: &str) -> Option<Self> {
        let rest = comment.split(Self::COMMENT_PREFIX).nth(1)?;
        let word: String = rest.chars().take_while(|c| c.is_ascii_alphabetic()).collect();
        match word.as_str() {
            "measured" => Some(Self::Measured),
            "simulated" => Some(Self::Simulated),
            "synthetic" => Some(Self::Synthetic),
            _ => None,
        }
    }
}

/// Identifies the input a report was computed from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct InputRef {
    /// File name (no directories).
    pub name: String,
    /// Size in bytes.
    pub bytes: u64,
    /// SHA-256 of the file contents, lower-case hex.
    pub sha256: String,
}

impl InputRef {
    /// The input `name` with contents `bytes`: their size and SHA-256.
    pub fn of(name: impl Into<String>, bytes: &[u8]) -> Self {
        Self { name: name.into(), bytes: bytes.len() as u64, sha256: sha256_hex(bytes) }
    }
}

/// `bytes` as lower-case hex, two digits each.
pub fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    bytes.iter().fold(String::with_capacity(bytes.len() * 2), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

/// SHA-256 of `bytes`, lower-case hex.
pub fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::Digest;
    hex(&sha2::Sha256::digest(bytes))
}

/// Metadata carried by every FlowLab report.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct ReportMeta {
    /// [`SCHEMA_VERSION`] of the report.
    pub schema_version: u32,
    /// Producing tool, `"ecat-flowlab"`.
    pub tool: String,
    /// Tool version (crate version).
    pub tool_version: String,
    /// Where the underlying data came from.
    pub source: Provenance,
    /// The analysed input.
    pub input: InputRef,
    /// Assumptions the analysis made that a reader must know to interpret it.
    pub assumptions: Vec<String>,
}

impl ReportMeta {
    /// Metadata for the current tool version.
    pub fn new(source: Provenance, input: InputRef, assumptions: Vec<String>) -> Self {
        Self {
            schema_version: SCHEMA_VERSION,
            tool: "ecat-flowlab".to_owned(),
            tool_version: env!("CARGO_PKG_VERSION").to_owned(),
            source,
            input,
            assumptions,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn provenance_marker_round_trip() {
        for p in [Provenance::Measured, Provenance::Simulated, Provenance::Synthetic] {
            let c = format!("generated; {}{}; seed=1", Provenance::COMMENT_PREFIX, p.as_str());
            assert_eq!(Provenance::from_comment(&c), Some(p));
        }
        assert_eq!(Provenance::from_comment("captured by TwinCAT"), None);
    }
}
